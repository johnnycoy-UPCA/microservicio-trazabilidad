package co.edu.clase.microservicio_trazabilidad.aplicacion.dto.respuesta;

import java.time.Instant;

public class EventoTrazabilidadDetalleDto {

    private String estadoAnterior;
    private String estadoNuevo;
    private Instant fechaEvento;
    private Long empleadoId;

    public EventoTrazabilidadDetalleDto() {
    }

    public String getEstadoAnterior() {
        return estadoAnterior;
    }

    public void setEstadoAnterior(String estadoAnterior) {
        this.estadoAnterior = estadoAnterior;
    }

    public String getEstadoNuevo() {
        return estadoNuevo;
    }

    public void setEstadoNuevo(String estadoNuevo) {
        this.estadoNuevo = estadoNuevo;
    }

    public Instant getFechaEvento() {
        return fechaEvento;
    }

    public void setFechaEvento(Instant fechaEvento) {
        this.fechaEvento = fechaEvento;
    }

    public Long getEmpleadoId() {
        return empleadoId;
    }

    public void setEmpleadoId(Long empleadoId) {
        this.empleadoId = empleadoId;
    }
}